export function errorText(code: string): string {
  return tr.errors[code] ?? tr.errors.internal;
}

/** "Ağustos 2022", "Nisan – Ağustos 2022", "2021 – 2023" for a date range. */
export function dateRange(from: string | null, to: string | null): string {
  if (!from && !to) return '';
  const a = (from ?? to)!;
  const b = (to ?? from)!;
  const [ya, ma] = [a.slice(0, 4), Number(a.slice(5, 7)) - 1];
  const [yb, mb] = [b.slice(0, 4), Number(b.slice(5, 7)) - 1];
  if (ya !== yb) return `${ya} – ${yb}`;
  if (ma === mb) return `${tr.months[ma]} ${ya}`;
  return `${tr.months[ma]} – ${tr.months[mb]} ${ya}`;
}

/** "14 Ağustos 2022, 19:00" */
export function longDate(iso: string | null): string {
  if (!iso) return '';
  const d = new Date(iso);
  return d.toLocaleString('tr-TR', { day: 'numeric', month: 'long', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}

export function formatDate(iso: string | null | undefined): string {
  if (!iso) return tr.user.never;
  return new Date(iso).toLocaleString('tr-TR', { dateStyle: 'short', timeStyle: 'short' });
}
